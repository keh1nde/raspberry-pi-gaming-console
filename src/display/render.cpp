void draw_char(uint32_t col, uint32_t row, char c, uint32_t fg, uint32_t bg) {
	// multiplying each coord by 8 ensures that each
	// cell is its own 8x8 block of pixels. Preventing
	// overlaps.
	const uint32_t x0 = col * 8;
	const uint32_t y0 = row * 8;

	// If char doesn't have a corresponding glyph
	if (c < 32 || c > 126) {
		for (int i = 0; i < 8; i++) {
			for (uint8_t bit = 0; bit < 8; bit++) {
				const int bit_set = font8x8_fallback[i] & (1 << bit);
				put_pixel(x0 + bit, y0 + i, bit_set ? fg : bg);
			}
		}
	} else {
		const uint8_t idx = c - 32;
		for (uint8_t glyph_row = 0; glyph_row < 8; glyph_row++) {
			for (uint8_t bit = 0; bit < 8; bit++) {
				const int bit_set = font8x8_basic[idx][glyph_row] & (1 << bit);
				put_pixel(x0 + bit, y0 + glyph_row, bit_set ? fg : bg);
			}
		}
	}
}

