#include <stdint.h>
#include "display/display.h"
#include "display/render.h"

void put_pixel(const uint32_t x, const uint32_t y, const uint32_t color) {
	uint8_t* row = reinterpret_cast<uint8_t*>(framebuffer_base) + y * framebuffer_pitch;
	uint32_t* pixel = reinterpret_cast<uint32_t*>(row + x * 4);
	*pixel = color;
}

uint32_t pack_color(const uint8_t r, const uint8_t g, const uint8_t b) {
	return static_cast<uint32_t>(b)
		| (static_cast<uint32_t>(g) << 8)
		| (static_cast<uint32_t>(r) << 16);
}

void fill_screen(const uint32_t color) {
	for (uint32_t y = 0; y < framebuffer_height; y++) {
		for (uint32_t x = 0; x < framebuffer_width; x++) {
			put_pixel(x, y, color);
		}
	}
}

void draw_horizontal_line(const uint32_t y, const uint32_t color) {
	for (uint32_t x = 0; x < framebuffer_width; x++) {
		put_pixel(x, y, color);
	}
}

